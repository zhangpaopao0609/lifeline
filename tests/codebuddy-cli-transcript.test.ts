import type { ChatElement } from '@lifeline/protocol';
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { describe, it } from 'node:test';
import {
  codebuddyProjectSlug,
  createCodebuddyCliFollow,
  projectCodebuddyCliGrowth,
  readCodebuddyCliGrowth,
} from '../packages/agent/src/drivers/acp/codebuddy-cli-transcript.js';

function human(id: string, text: string): ChatElement {
  return { type: 'human', id, flatIndex: 0, text, mentions: [] };
}

function line(record: unknown): string {
  return `${JSON.stringify(record)}\n`;
}

describe('codebuddyProjectSlug', () => {
  it('turns an absolute directory into the CodeBuddy project folder name', () => {
    assert.equal(
      codebuddyProjectSlug('/Users/zhangpaopao/Desktop/tx/developers/mmbizwxadevelopersnodelogicsvr'),
      'Users-zhangpaopao-Desktop-tx-developers-mmbizwxadevelopersnodelogicsvr',
    );
    assert.equal(
      codebuddyProjectSlug('/Users/zhangpaopao/.guanlan/sub'),
      'Users-zhangpaopao-.guanlan-sub',
    );
  });
});

describe('projectCodebuddyCliGrowth', () => {
  it('keeps a torn line until the newline arrives', () => {
    const follow = createCodebuddyCliFollow();
    const partial = projectCodebuddyCliGrowth(
      follow,
      Buffer.from('{"type":"message","id":"u1","role":"user","__codebuddyLocal":true,"content":[{"type":"input_text","text":"广州"}]}'),
      [],
      new Set(),
    );
    assert.deepEqual(partial.append, []);
    const done = projectCodebuddyCliGrowth(follow, Buffer.from('\n'), [], new Set());
    assert.equal(done.append.length, 1);
    assert.equal(done.append[0]?.type, 'human');
    assert.equal(done.append[0]?.type === 'human' ? done.append[0].text : '', '广州');
  });

  it('projects a finished turn and skips bookkeeping lines', () => {
    const follow = createCodebuddyCliFollow();
    const raw = [
      line({ type: 'session-meta', id: 'meta-1' }),
      line({
        type: 'message',
        id: 'user-1',
        role: 'user',
        __codebuddyLocal: true,
        timestamp: 1793245659111,
        content: [{ type: 'input_text', text: '今天天气怎么样' }],
      }),
      line({
        type: 'reasoning',
        id: 'thought-1',
        rawContent: [{ type: 'reasoning_text', text: '先问城市' }],
      }),
      line({
        type: 'function_call',
        id: 'call-row-1',
        callId: 'call-1',
        name: 'WebSearch',
        arguments: JSON.stringify({ query: '广州 今天 天气' }),
      }),
      line({
        type: 'function_call_result',
        id: 'result-1',
        callId: 'call-1',
        status: 'completed',
        output: { type: 'text', text: '晴' },
      }),
      line({
        type: 'message',
        id: 'assistant-1',
        role: 'assistant',
        status: 'completed',
        content: [{ type: 'output_text', text: '广州今天晴。' }],
      }),
      line({
        type: 'message',
        id: 'assistant-open',
        role: 'assistant',
        content: [{ type: 'output_text', text: '还在写' }],
      }),
    ].join('');
    const projected = projectCodebuddyCliGrowth(follow, Buffer.from(raw), [], new Set());
    assert.deepEqual(projected.patches, []);
    assert.deepEqual(projected.append.map(element => element.type), ['human', 'thought', 'tool', 'assistant']);
    const tool = projected.append[2];
    assert.equal(tool?.type, 'tool');
    if (tool?.type === 'tool') {
      assert.equal(tool.action, 'Search(广州 今天 天气)');
      assert.equal(tool.status, 'completed');
      assert.equal(tool.details, '晴');
      assert.equal(tool.toolCallId.startsWith('disk-'), true);
    }
    const assistant = projected.append[3];
    assert.equal(assistant?.type === 'assistant' ? assistant.text : '', '广州今天晴。');
    const again = projectCodebuddyCliGrowth(follow, Buffer.from(raw), [], new Set());
    assert.deepEqual(again.append, []);
  });

  it('keeps locally typed text, restores a slash command, and drops other injected user records', () => {
    const follow = createCodebuddyCliFollow();
    const raw = [
      line({
        type: 'message',
        id: 'caveat-1',
        role: 'user',
        content: [{
          type: 'input_text',
          text: '<system-reminder data-role="command-caveat">Caveat: The messages below were generated by the user while running local commands.</system-reminder>',
        }],
      }),
      line({
        type: 'message',
        id: 'injected-1',
        role: 'user',
        content: [{ type: 'input_text', text: '这是另一段插进来的说明' }],
      }),
      line({
        type: 'message',
        id: 'command-model',
        role: 'user',
        content: [{ type: 'input_text', text: '<command-name>/model</command-name>' }],
      }),
      line({
        type: 'message',
        id: 'command-1',
        role: 'user',
        content: [{
          type: 'input_text',
          text: '<command-message>diagnose</command-message>\n<command-name>/diagnose</command-name>\n<command-args>recently the PR data does not update</command-args>',
        }],
      }),
      line({
        type: 'message',
        id: 'typed-1',
        role: 'user',
        __codebuddyLocal: true,
        content: [{ type: 'input_text', text: '谢谢' }],
      }),
    ].join('');
    const projected = projectCodebuddyCliGrowth(follow, Buffer.from(raw), [], new Set());
    assert.deepEqual(
      projected.append.flatMap(element => element.type === 'human' ? [element.text] : []),
      ['/model', '/diagnose recently the PR data does not update', '谢谢'],
    );
  });

  it('claims an existing message once and still appends a later copy', () => {
    const follow = createCodebuddyCliFollow();
    const messages = [human('human:1', '你好')];
    const claimable = new Set(['human:1']);
    const echo = projectCodebuddyCliGrowth(
      follow,
      Buffer.from(line({
        type: 'message',
        id: 'user-echo',
        role: 'user',
        content: [{ type: 'input_text', text: '你好' }],
        __codebuddyLocal: true,
      })),
      messages,
      claimable,
    );
    assert.deepEqual(echo.append, []);
    const extra = projectCodebuddyCliGrowth(
      follow,
      Buffer.from(line({
        type: 'message',
        id: 'user-2',
        role: 'user',
        content: [{ type: 'input_text', text: '你好' }],
        __codebuddyLocal: true,
      })),
      messages,
      claimable,
    );
    assert.equal(extra.append.length, 1);
    assert.equal(extra.append[0]?.type === 'human' ? extra.append[0].text : '', '你好');
    assert.equal(extra.append[0]?.id.startsWith('disk-'), true);
  });

  it('patches a tool when its result arrives in a later chunk', () => {
    const follow = createCodebuddyCliFollow();
    const opened = projectCodebuddyCliGrowth(
      follow,
      Buffer.from(line({
        type: 'function_call',
        id: 'call-row',
        callId: 'call-9',
        name: 'Write',
        arguments: JSON.stringify({ file_path: '/work/AGENTS.md', content: 'hi' }),
      })),
      [],
      new Set(),
    );
    assert.equal(opened.append.length, 1);
    const tool = opened.append[0];
    assert.equal(tool?.type, 'tool');
    if (tool?.type !== 'tool')
      return;
    assert.equal(tool.status, 'loading');
    assert.equal(tool.filename, '/work/AGENTS.md');
    const finished = projectCodebuddyCliGrowth(
      follow,
      Buffer.from(line({
        type: 'function_call_result',
        id: 'result-9',
        callId: 'call-9',
        status: 'completed',
        output: { type: 'text', text: 'wrote' },
      })),
      [],
      new Set(),
    );
    assert.deepEqual(finished.append, []);
    assert.deepEqual(finished.patches, [{ id: tool.id, status: 'completed', details: 'wrote' }]);
  });
});

describe('readCodebuddyCliGrowth', () => {
  it('reads only the bytes appended after the last offset', () => {
    const root = mkdtempSync(path.join(tmpdir(), 'lifeline-cb-jsonl-'));
    const file = path.join(root, 'session.jsonl');
    const follow = createCodebuddyCliFollow();
    assert.equal(readCodebuddyCliGrowth(file, follow), undefined);
    writeFileSync(file, 'one\n');
    assert.equal(readCodebuddyCliGrowth(file, follow)?.toString(), 'one\n');
    assert.equal(readCodebuddyCliGrowth(file, follow), undefined);
    writeFileSync(file, 'one\ntwo\n');
    assert.equal(readCodebuddyCliGrowth(file, follow)?.toString(), 'two\n');
  });
});
